import { chromium } from '@playwright/test';
const BASE = 'https://mertdas24.github.io/sanal-garaj/';
const b = await chromium.launch({ channel: 'chrome' });
const pg = await b.newPage({ viewport: { width: 1400, height: 900 } });
const issues = [];
pg.on('console', (m) => { if (m.type() === 'error' || /Content Security Policy|Refused/i.test(m.text())) issues.push(m.text().slice(0, 160)); });
pg.on('pageerror', (e) => issues.push('pageerror ' + e.message));
pg.on('response', (r) => { if (r.status() >= 400) issues.push(`${r.status()} ${r.url()}`); });
await pg.goto(BASE);
console.log('kartlar', await pg.locator('.grid > li').count());
console.log('CSP', !!(await pg.locator('meta[http-equiv="Content-Security-Policy"]').count()));
console.log('og:image', await pg.locator('meta[property="og:image"]').getAttribute('content'));
await pg.goto(BASE + '#/arac/lamborghini-gallardo?env=sunset&wt=dark&cc=f2c40f&f=p&p=e8650f');
await pg.waitForSelector('.viewer canvas'); await pg.waitForSelector('.viewer__overlay', { state: 'detached', timeout: 60000 });
await pg.getByRole('radio', { name: 'Hızlı' }).click();
await pg.getByRole('button', { name: 'Fotogerçekçi görüntü' }).click();
await pg.waitForSelector('text=Fotogerçekçi görüntü hazır', { timeout: 300000 });
await pg.goto(BASE + '#/hakkinda');
await pg.waitForSelector('text=Sanal Garaj nasıl yapıldı?');
const og = await fetch(BASE + 'og-image.jpg');
console.log('og-image', og.status, og.headers.get('content-type'));
console.log('sorunlar', issues.length ? issues : 'yok');
await b.close();

import fs from 'node:fs';
import { chromium } from '@playwright/test';
const [hash, out, wait = '90000'] = process.argv.slice(2);
const b = await chromium.launch({ channel: 'chrome', args: process.env.ANGLE ? [`--use-angle=${process.env.ANGLE}`] : [] });
const pg = await b.newPage({ viewport: { width: 1400, height: 900 } });
pg.on('pageerror', (e) => console.log('pageerror', e.message));
pg.on('console', (m) => { if (m.type() === 'error') console.log('console', m.text().slice(0, 300)); });
await pg.goto((process.env.BASE ?? 'http://localhost:5199/') + hash);
await pg.waitForSelector('.viewer canvas', { timeout: 60000 });
await pg.waitForSelector('.viewer__overlay', { state: 'detached', timeout: 60000 });
await pg.getByRole('button', { name: 'Fotogerçekçi görüntü' }).click();
const t0 = Date.now();
await pg.waitForSelector('text=Fotogerçekçi görüntü hazır', { timeout: +wait }).catch(() => {});
console.log('süre', ((Date.now() - t0) / 1000).toFixed(1), 's', await pg.locator('.pt-status p').textContent());
const raw = await pg.evaluate(() => document.querySelector('.pt-canvas')?.toDataURL('image/png'));
if (raw) fs.writeFileSync(out.replace('.png', '_raw.png'), Buffer.from(raw.split(',')[1], 'base64'));
console.log('canvas', await pg.evaluate(() => { const c = document.querySelector('.pt-canvas'); return c ? [c.width, c.height, c.clientWidth, c.clientHeight] : null; }));
await pg.addStyleTag({ content: '.pt-status,.viewer__tools{display:none!important}' });
await pg.locator('.viewer').screenshot({ path: out });
await b.close();

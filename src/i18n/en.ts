/** Türkçe sayı biçimini İngilizceye çevirir: 197.630 → 197,630; 3,8 → 3.8 */
export function enNumber(text: string): string {
  return text.replace(/(\d),(\d)/g, '$1§$2').replace(/(\d)\.(\d{3})/g, '$1,$2').replace(/§/g, '.');
}
const inner = (text: string) => EN[text] ?? EN[`${text}.`] ?? text;

